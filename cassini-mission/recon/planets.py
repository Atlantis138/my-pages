"""Standish (JPL) approximate Keplerian elements, J2000 ecliptic, valid 1800-2050. Same formulas as the page."""
import numpy as np
AU = 149597870.7
EL = {  # a, e, I, L, varpi, Omega ; rates per Julian century
 '299': ([0.72333566, 0.00677672, 3.39467605, 181.97909950, 131.60246718, 76.67984255], [0.00000390, -0.00004107, -0.00078890, 58517.81538729, 0.00268329, -0.27769418]),
 '399': ([1.00000261, 0.01671123, -0.00001531, 100.46457166, 102.93768193, 0.0], [0.00000562, -0.00004392, -0.01294668, 35999.37244981, 0.32327364, 0.0]),
 '499': ([1.52371034, 0.09339410, 1.84969142, -4.55343205, -23.94362959, 49.55953891], [0.00001847, 0.00007882, -0.00813131, 19140.30268499, 0.44441088, -0.29257343]),
 '599': ([5.20288700, 0.04838624, 1.30439695, 34.39644051, 14.72847983, 100.47390909], [-0.00011607, -0.00013253, -0.00183714, 3034.74612775, 0.21252668, 0.20469106]),
 '699': ([9.53667594, 0.05386179, 2.48599187, 49.95424423, 92.59887831, 113.66242448], [-0.00125060, -0.00050991, 0.00193609, 1222.49362201, -0.41897216, -0.28867794]),
}
def planet(p, jd):
    T = (np.atleast_1d(jd) - 2451545.0) / 36525
    e0, r = EL[p]; a, e, I, L, w, O = [e0[k] + r[k] * T for k in range(6)]
    d = np.pi / 180; M = np.mod((L - w) * d + np.pi, 2 * np.pi) - np.pi
    E = M.copy()
    for _ in range(30): E = E - (E - e * np.sin(E) - M) / (1 - e * np.cos(E))
    x = a * (np.cos(E) - e); y = a * np.sqrt(1 - e * e) * np.sin(E)
    om = (w - O) * d; O = O * d; I = I * d
    co, so, cO, sO, cI, sI = np.cos(om), np.sin(om), np.cos(O), np.sin(O), np.cos(I), np.sin(I)
    X = (co * cO - so * sO * cI) * x + (-so * cO - co * sO * cI) * y
    Y = (co * sO + so * cO * cI) * x + (-so * sO + co * cO * cI) * y
    Z = (so * sI) * x + (co * sI) * y
    return np.stack([X, Y, Z], -1) * AU
